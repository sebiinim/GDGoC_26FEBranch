import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'

// Vite 설정 파일입니다.
export default defineConfig({
  plugins: [react()],

  server: {
    // ==============================================================
    // 개발 서버 프록시 — 2회차의 숨은 조력자
    // ==============================================================
    // 화면에서 fetch('/api/words/apple') 처럼 "상대경로"로 부르면,
    // Vite 개발 서버(5173)가 그 요청을 아래 주소(3001, 미니 API)로
    // 대신 전달해 줍니다.
    //
    // 왜 이게 필요한가:
    //   미니 API(3001)를 브라우저에서 직접 부르면 "출처(origin)"가 달라서
    //   브라우저가 응답을 막습니다. (CORS — 3회차에서 제대로 다룹니다)
    //   프록시를 거치면 브라우저 입장에서는 전부 5173 = 같은 출처라
    //   아무 문제가 없습니다.
    //
    // ★ 3회차 복선:
    //   "개발 중에는 Vite가 이렇게 대신 전달해 줬는데,
    //    npm run build 로 만든 결과물에는 Vite가 없다. 그럼 누가 해주지?"
    //   → 그 답(nginx 리버스 프록시)이 3회차의 주제입니다.
    proxy: {
      '/api': 'http://localhost:3001',
    },
  },
})
